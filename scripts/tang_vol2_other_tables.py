def calc(a, b): return f'{a/b*100:.2f}%' if b else ''
def chk(label, printed, a, b, tol=0.011):
    """印本比率與 a/b 相差逾 tol 個百分點者記入 problems。printed 為 '' 或 None 時不核。"""
    if printed in ('', None) or not b: return
    if abs(float(printed.rstrip('%')) - a / b * 100) > tol:
        problems.append(f'{label}：印 {printed}，{a}/{b} 為 {calc(a, b)}')

