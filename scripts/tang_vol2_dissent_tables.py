def pct(a, b): return a / b * 100 if b else None
def rate_ok(printed, a, b, tol=0.011):
    """印本比率與重算相差逾 tol 個百分點者回傳重算值字串，否則回 None。"""
    if printed in ('', None) or not b: return None
    c = a / b * 100
    return None if abs(float(printed.rstrip('%')) - c) <= tol else f'{c:.2f}%'
def parse_star(s):
    return [(int(x.strip().rstrip('*')), x.strip().endswith('*')) for x in s.split(',') if x.strip()]
