def parse(s):
    """'213(第一部份)[1], 216[1], 217' → [(213,'第一部份',1), ...]；無 [] 者人次 0。"""
    res = []
    for tok in [t.strip() for t in s.split(',') if t.strip()]:
        m = re.fullmatch(r'(\d+)(?:\(([^)]*)\))?(?:\[(\d+)\])?', tok)
        if not m: raise ValueError(tok)
        res.append((int(m[1]), m[2] or '', int(m[3] or 0)))
    return res

def w(name, header, rows):
    with open(os.path.join(out, name), 'w', newline='') as f:
        c = csv.writer(f, delimiter='\t', lineterminator='\n'); c.writerow(header); c.writerows(rows)

