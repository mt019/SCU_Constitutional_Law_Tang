edits = []
from collections import defaultdict
bycue = defaultdict(list)
for c, o, n, b in S:
    bycue[c].append((o, n, b))
for c in sorted(bycue):
    t = T[c]
    spans = []
    for o, n, b in bycue[c]:
        i = 0; found = False
        while True:
            j = t.find(o, i)
            if j < 0: break
            spans.append([j, j + len(o), o, n, b]); found = True
            i = j + len(o)
        if not found: sys.exit(f'NOT FOUND {c} {o}')
    spans.sort()
    for a, b2 in zip(spans, spans[1:]):
        if a[1] > b2[0]: sys.exit(f'OVERLAP {c} {a[2]} {b2[2]}')
    # expand each span to unique window, merging if collide
    wins = []
    for s in spans:
        L, R = s[0], s[1]
        while t.count(t[L:R]) > 1:
            if R < len(t): R += 1
            if t.count(t[L:R]) > 1 and L > 0: L -= 1
        wins.append([L, R, [s]])
    merged = []
    for w in wins:
        if merged and w[0] < merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], w[1]); merged[-1][2] += w[2]
        else:
            merged.append(w)
    for L, R, ss in merged:
        before = t[L:R]
        assert t.count(before) == 1, (c, before)
        after = ''; pos = L
        for s in ss:
            after += t[pos:s[0]] + s[3]; pos = s[1]
        after += t[pos:R]
        basis = '；'.join(dict.fromkeys(s[4] for s in ss))
        edits.append((c, before, after, basis))

